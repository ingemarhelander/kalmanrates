function kalmanOptimizeApp
% Enkelt gränssnitt för att välja inställningar och starta optimeringen.

% Hitta projektmapparna utifrån var den här filen ligger.
scriptDir = fileparts(mfilename('fullpath'));
projectRoot = fileparts(scriptDir);

% Lägg till projektets mappar så att readConfig och övriga funktioner hittas.
run(fullfile(projectRoot, 'setupPaths.m'));

% Läs standardinställningarna från configfilen.
configPath = fullfile(scriptDir, 'kalmanOptimizeMain.config');
uiConfig = addMissingConfigValues(readConfig(configPath));

% Skapa fönstret.
fig = uifigure( ...
    'Name', 'Kalmanoptimering', ...
    'Position', [100 100 470 470]);

uilabel(fig, ...
    'Text', 'Inställningar för Kalmanoptimering', ...
    'FontSize', 16, ...
    'FontWeight', 'bold', ...
    'Position', [25 420 420 25]);

% Inställningsfält.
uilabel(fig, 'Text', 'Max iterationer', ...
    'Position', [25 370 180 22]);
maxIterField = uieditfield(fig, 'numeric', ...
    'Position', [220 370 210 22], ...
    'Limits', [1 Inf], ...
    'RoundFractionalValues', 'on', ...
    'Value', uiConfig.maxIter);

uilabel(fig, 'Text', 'Noisy size', ...
    'Position', [25 330 180 22]);
noisySizeField = uieditfield(fig, 'numeric', ...
    'Position', [220 330 210 22], ...
    'Limits', [1 Inf], ...
    'RoundFractionalValues', 'on', ...
    'Value', uiConfig.noisy_size);

uilabel(fig, 'Text', 'Mu', ...
    'Position', [25 290 180 22]);
muField = uieditfield(fig, 'numeric', ...
    'Position', [220 290 210 22], ...
    'Limits', [0 Inf], ...
    'Value', uiConfig.mu);

uilabel(fig, 'Text', 'Antal startpunkter', ...
    'Position', [25 250 180 22]);
numStartsField = uieditfield(fig, 'numeric', ...
    'Position', [220 250 210 22], ...
    'Limits', [1 Inf], ...
    'RoundFractionalValues', 'on', ...
    'Value', uiConfig.numStarts);

uilabel(fig, 'Text', 'Seed', ...
    'Position', [25 210 180 22]);
seedField = uieditfield(fig, 'numeric', ...
    'Position', [220 210 210 22], ...
    'Limits', [0 Inf], ...
    'RoundFractionalValues', 'on', ...
    'Value', uiConfig.seed);

uilabel(fig, 'Text', 'Startperturbation', ...
    'Position', [25 170 180 22]);
perturbationField = uieditfield(fig, 'numeric', ...
    'Position', [220 170 210 22], ...
    'Limits', [0 Inf], ...
    'Value', uiConfig.startPerturbation);

uilabel(fig, 'Text', 'Line search-metod', ...
    'Position', [25 130 180 22]);
lineSearchDropDown = uidropdown(fig, ...
    'Items', {'polynomial', 'backtracking'}, ...
    'Position', [220 130 210 22], ...
    'Value', char(uiConfig.lineSearch));

% Visar status och eventuella fel.
statusLabel = uilabel(fig, ...
    'Text', 'Inställningarna lästes från configfilen.', ...
    'Position', [25 20 420 40], ...
    'WordWrap', 'on');

% Läs in configfilen igen och återställ fälten.
uibutton(fig, 'push', ...
    'Text', 'Läs om config', ...
    'Position', [25 75 150 32], ...
    'ButtonPushedFcn', @loadConfigButtonPushed);

% Kör optimeringen med värdena som står i fälten.
runButton = uibutton(fig, 'push', ...
    'Text', 'Kör optimering', ...
    'Position', [280 75 150 32], ...
    'ButtonPushedFcn', @runButtonPushed);

    function setFieldsFromConfig()
        % Kopierar configvärdena till gränssnittets fält.
        maxIterField.Value = uiConfig.maxIter;
        noisySizeField.Value = uiConfig.noisy_size;
        muField.Value = uiConfig.mu;
        numStartsField.Value = uiConfig.numStarts;
        seedField.Value = uiConfig.seed;
        perturbationField.Value = uiConfig.startPerturbation;
        lineSearchDropDown.Value = char(uiConfig.lineSearch);
    end

    function loadConfigButtonPushed(~, ~)
        % Läser in värdena från configfilen på nytt.
        try
            uiConfig = addMissingConfigValues(readConfig(configPath));
            setFieldsFromConfig();
            statusLabel.Text = 'Configfilen lästes in.';
        catch ME
            statusLabel.Text = ['Fel vid inläsning: ' ME.message];
            uialert(fig, ME.message, 'Kunde inte läsa config');
        end
    end

    function runButtonPushed(~, ~)
        % Bygg en struct av värdena i gränssnittet.
        override = struct( ...
            'maxIter', maxIterField.Value, ...
            'noisy_size', noisySizeField.Value, ...
            'mu', muField.Value, ...
            'numStarts', numStartsField.Value, ...
            'seed', seedField.Value, ...
            'startPerturbation', perturbationField.Value, ...
            'lineSearch', lineSearchDropDown.Value);

        % Visa status innan den tidskrävande optimeringen startar.
        runButton.Enable = 'off';
        statusLabel.Text = 'Optimeringen körs. Se Command Window för utskrifter.';
        drawnow;

        try
            runKalmanMainFromApp(scriptDir, override);
            statusLabel.Text = ...
                'Körningen är klar. Resultat och tid visas i Command Window.';
        catch ME
            statusLabel.Text = ['Körningen misslyckades: ' ME.message];
            uialert(fig, ME.message, 'Fel vid optimering');
        end

        runButton.Enable = 'on';
    end
end

function config = addMissingConfigValues(config)
% Lägger till standardvärden om någon av raderna saknas i configfilen.

defaults = struct( ...
    'maxIter', 100, ...
    'noisy_size', 3, ...
    'mu', 1e-2, ...
    'numStarts', 1, ...
    'seed', 1, ...
    'startPerturbation', 0.1, ...
    'lineSearch', 'polynomial');

names = fieldnames(defaults);
for k = 1:numel(names)
    if ~isfield(config, names{k})
        config.(names{k}) = defaults.(names{k});
    end
end
end

function runKalmanMainFromApp(scriptDir, override)
% Kör huvudskriptet i en egen funktion så det kan skapa sina variabler.
kalmanOptimizeMainConfigOverride = override; %#ok<NASGU>
run(fullfile(scriptDir, 'kalmanOptimizeMain.m'));
end